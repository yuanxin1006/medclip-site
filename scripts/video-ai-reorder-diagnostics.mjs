const SUBSTAGES_BY_GATE = Object.freeze({
  OWNED_MEDIA_SETUP: OWNED_MEDIA_SUBSTAGES,
  PROJECT_GENERATION: Object.freeze(['PROJECT_PERSISTENCE_WAIT']),
  PROJECT_OPEN: PROJECT_OPEN_SUBSTAGES,
  ASSET_REPLACEMENT: ASSET_REPLACEMENT_SUBSTAGES,
  LIVE_ACCEPTANCE: LIVE_ACCEPTANCE_SUBSTAGES,
});
function safeSubstage(gate, substage) {
  return SUBSTAGES_BY_GATE[gate]?.includes(substage) ? substage : undefined;
}
export class SafeAcceptanceGateError extends Error {
  constructor(gate, code = GATE_CODES[gate], substage) {
    const g = Object.hasOwn(GATE_CODES,gate) ? gate : 'INTERNAL';
    const c = SAFE_CODES.includes(code) ? code : 'INTERNAL_SAFE_FAILURE';
    const s = safeSubstage(g,substage);
    super(`${g}:${c}`);
    Object.defineProperties(this,{gate:{value:g,enumerable:true},code:{value:c,enumerable:true},substage:{value:s,enumerable:true}});
  }
  toJSON() { return {gate:this.gate,code:this.code,...(this.substage ? {substage:this.substage} : {})}; }
}
export function safeError(error,gate='INTERNAL',substage) { return error instanceof SafeAcceptanceGateError ? error : new SafeAcceptanceGateError(gate,undefined,substage); }
export async function gateScope(initial,action) {
  let gate=initial, substage;
  try { return await action(
    next=>{gate=Object.hasOwn(GATE_CODES,next)?next:'INTERNAL';substage=undefined;},
    next=>{substage=safeSubstage(gate,next);},
  ); }
  catch(error) { throw safeError(error,gate,substage); }
}
export function formatAcceptanceFailure(error,preflight=true) {
  const e=safeError(error);
  return [preflight?'REORDER_PREFLIGHT_BLOCKED':'REORDER_ACCEPTANCE_BLOCKED',`GATE = ${e.gate}`,`CODE = ${e.code}`,...(e.substage?[`SUBSTAGE = ${e.substage}`]:[]),...(preflight?['PROVIDER_CALLS = 0']:[]),'RETRY = 0','FALLBACK = NONE',...(e.cleanupFailed===true?['CLEANUP_STATUS = FAILED']:[])].join('\n');
}
